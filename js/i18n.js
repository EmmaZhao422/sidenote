export const DICT = { en, zh };

export function getLang() {
  const chosen = store.state.settings.lang;
  if (chosen === 'en' || chosen === 'zh') return chosen;
  const nav = (typeof navigator !== 'undefined' && navigator.language) || 'en';
  return nav.toLowerCase().startsWith('zh') ? 'zh' : 'en';
}

export function t(key, vars) {
  const lang = getLang();
  let text = DICT[lang][key] ?? DICT.en[key] ?? key;
  if (vars) {
    // {n|thought|thoughts} picks the singular or plural word for English
    text = text.replace(/\{(\w+)\|([^|}]*)\|([^}]*)\}/g, (m, name, one, many) => (Number(vars[name]) === 1 ? one : many));
    text = text.replace(/\{(\w+)\}/g, (m, name) => (name in vars ? String(vars[name]) : m));
  }
  return text;
}
